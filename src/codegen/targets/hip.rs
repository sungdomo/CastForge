//! AMD ROCm HIP C++ (`.hip.cpp`) GPU Kernel Code Generator (`CodegenTarget::Hip`).

use crate::codegen::backend::emit_c_like_loop_stmt;
use crate::codegen::{LoopModule, TargetConfig, lower_to_loop_ir};
use crate::ir::Module;
use anyhow::Result;
use std::fmt::Write;

/// Emits AMD ROCm HIP C++ (`.hip.cpp`) GPU kernels for `module`.
pub fn emit_hip_module_with_config(module: &Module, base_config: &TargetConfig) -> Result<String> {
    let loop_mod = lower_to_loop_ir(module, base_config);
    let cfg = base_config.with_module_attributes(module);
    emit_hip_from_loop_ir(&loop_mod, &cfg)
}

/// Emits AMD ROCm HIP C++ (`.hip.cpp`) GPU kernels from a lowered [`LoopModule`].
pub fn emit_hip_from_loop_ir(loop_mod: &LoopModule, config: &TargetConfig) -> Result<String> {
    let block_dim = config.wgsl_workgroup_size.max(64);
    let mut out = String::new();
    writeln!(out, "// Auto-generated by CastForge AMD ROCm HIP Backend")?;
    writeln!(out, "#include <hip/hip_runtime.h>")?;
    writeln!(out, "#include <math.h>\n")?;

    for kernel in &loop_mod.kernels {
        let mut sig_params: Vec<String> = kernel
            .params
            .iter()
            .map(|(n, _)| format!("const float* __restrict__ {n}"))
            .collect();
        sig_params.push(format!("float* __restrict__ {}", kernel.output.0));
        writeln!(
            out,
            "extern \"C\" __global__ void {}_hip_kernel({}) {{",
            kernel.name,
            sig_params.join(", ")
        )?;
        writeln!(
            out,
            "    const int tid = (int)(blockIdx.x * blockDim.x + threadIdx.x);"
        )?;
        for stmt in &kernel.body {
            emit_c_like_loop_stmt(&mut out, stmt, &kernel.output.0, "tid", 1, true)?;
        }
        writeln!(out, "}}\n")?;

        let mut host_params: Vec<String> = kernel
            .params
            .iter()
            .map(|(n, _)| format!("const float* {n}"))
            .collect();
        host_params.push(format!("float* {}", kernel.output.0));
        let arg_names: Vec<String> = kernel
            .params
            .iter()
            .map(|(n, _)| n.clone())
            .chain(std::iter::once(kernel.output.0.clone()))
            .collect();
        let total = kernel.output.1.max(1);
        writeln!(
            out,
            "extern \"C\" void {}_hip_launch({}) {{",
            kernel.name,
            host_params.join(", ")
        )?;
        writeln!(out, "    const unsigned int threads = {block_dim}u;")?;
        writeln!(
            out,
            "    const unsigned int blocks = ({total}u + threads - 1u) / threads;"
        )?;
        writeln!(
            out,
            "    hipLaunchKernelGGL({}_hip_kernel, dim3(blocks), dim3(threads), 0, 0, {});",
            kernel.name,
            arg_names.join(", ")
        )?;
        writeln!(out, "}}\n")?;
    }
    Ok(out)
}
