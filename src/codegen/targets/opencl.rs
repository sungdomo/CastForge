//! Khronos OpenCL C (`.cl`) GPU/FPGA Kernel Code Generator (`CodegenTarget::OpenCl`).

use crate::codegen::backend::emit_c_like_loop_stmt;
use crate::codegen::{LoopModule, TargetConfig, lower_to_loop_ir};
use crate::ir::Module;
use anyhow::Result;
use std::fmt::Write;

/// Emits Khronos OpenCL C (`.cl`) compute kernels for `module`.
pub fn emit_opencl_module_with_config(
    module: &Module,
    base_config: &TargetConfig,
) -> Result<String> {
    let loop_mod = lower_to_loop_ir(module, base_config);
    emit_opencl_from_loop_ir(&loop_mod)
}

/// Emits Khronos OpenCL C (`.cl`) compute kernels from a lowered [`LoopModule`].
pub fn emit_opencl_from_loop_ir(loop_mod: &LoopModule) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "/* Auto-generated by CastForge OpenCL C Backend */")?;

    for kernel in &loop_mod.kernels {
        let mut sig_params: Vec<String> = kernel
            .params
            .iter()
            .map(|(n, _)| format!("__global const float* restrict {n}"))
            .collect();
        sig_params.push(format!("__global float* restrict {}", kernel.output.0));
        writeln!(
            out,
            "__kernel void {}_opencl_kernel({}) {{",
            kernel.name,
            sig_params.join(", ")
        )?;
        writeln!(out, "    const int gid = (int)get_global_id(0);")?;
        for stmt in &kernel.body {
            emit_c_like_loop_stmt(&mut out, stmt, &kernel.output.0, "gid", 1, true)?;
        }
        writeln!(out, "}}\n")?;
    }
    Ok(out)
}
