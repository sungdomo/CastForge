//! WebGPU WGSL Compute Shader Code Generator (`CodegenTarget::Wgsl`).

use crate::codegen::{TargetConfig, build_memory_plan, tensor_len, tensor_shape_dims, value_ident};
use crate::ir::{Attribute, DType, Module, OpId, Operation, ValueId};
use crate::stablehlo::StableHloOp;
use anyhow::Result;
use std::collections::HashMap;
use std::fmt::Write;

/// WebGPU WGSL Compute Shader Generator (`CodegenTarget::Wgsl`).
pub fn emit_wgsl_module(module: &Module) -> Result<String> {
    emit_wgsl_module_with_config(module, &TargetConfig::default())
}

/// WebGPU WGSL Compute Shader Generator parameterized by [`TargetConfig`].
pub fn emit_wgsl_module_with_config(module: &Module, config: &TargetConfig) -> Result<String> {
    let mut out = String::new();
    let plan = build_memory_plan(module);
    writeln!(
        out,
        "// Auto-generated by CastForge Codegen (Target: WebGPU WGSL)"
    )?;
    writeln!(
        out,
        "// Constant Weights: {} B | Activation Workspace: {} B \
         (Naive: {} B, Saved: {} B across {} arena slots)",
        plan.total_constant_bytes,
        plan.total_activation_bytes,
        plan.naive_activation_bytes,
        plan.saved_activation_bytes(),
        plan.reusable_slot_count
    )?;

    if let Some(&fn_op_id) = module.functions().first() {
        emit_wgsl_func(module, fn_op_id, config, &mut out)?;
    }

    Ok(out)
}

fn wgsl_idx(module: &Module, vid: ValueId, res_len: usize, name: &str, idx_var: &str) -> String {
    let len = tensor_len(module, vid).max(1);
    if len == 1 {
        format!("{name}[0u]")
    } else if len < res_len {
        format!("{name}[{idx_var} % {len}u]")
    } else {
        format!("{name}[{idx_var}]")
    }
}

fn emit_wgsl_func(
    module: &Module,
    fn_op_id: OpId,
    config: &TargetConfig,
    out: &mut String,
) -> Result<()> {
    let fn_op = &module.ops[fn_op_id];
    let region_id = fn_op.regions[0];
    let block_id = module.regions[region_id].blocks[0];
    let block = &module.blocks[block_id];

    let mut names: HashMap<ValueId, String> = HashMap::new();
    let mut counter = 0usize;

    for (b_idx, &arg_id) in block.arguments.iter().enumerate() {
        let name = format!("input_{b_idx}");
        names.insert(arg_id, name.clone());
        writeln!(
            out,
            "@group(0) @binding({b_idx}) var<storage, read> {name}: array<f32>;"
        )?;
    }
    let out_binding = block.arguments.len();
    writeln!(
        out,
        "@group(0) @binding({out_binding}) var<storage, read_write> output_0: array<f32>;\n"
    )?;

    // Emit module-scope constant arrays
    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if !op.is_op("stablehlo", "constant") {
            continue;
        }
        let Some(&res_val) = op.results.first() else {
            continue;
        };
        let res_name = value_ident(module, res_val, &mut names, &mut counter);
        let res_len = tensor_len(module, res_val);
        let Some(t_ty) = module.values[res_val].ty.as_tensor() else {
            continue;
        };
        let val_attr = op.attributes.get("value");
        if let DType::QuantUniform { .. } = &t_ty.dtype {
            let q_vals = val_attr
                .and_then(|a| module.tensor_store.resolve_i8_attr(a, res_len))
                .unwrap_or_else(|| vec![0; res_len]);
            let elems: Vec<String> = q_vals.iter().map(|v| format!("{v}i")).collect();
            writeln!(
                out,
                "const {res_name}: array<i32, {res_len}> = array<i32, {res_len}>({});",
                elems.join(", ")
            )?;
        } else {
            let vals = val_attr
                .and_then(|a| module.tensor_store.resolve_f32_attr(a, res_len))
                .unwrap_or_else(|| vec![0.0; res_len]);
            let elems: Vec<String> = vals.iter().map(|v| format!("{v:.6}")).collect();
            writeln!(
                out,
                "const {res_name}: array<f32, {res_len}> = array<f32, {res_len}>({});",
                elems.join(", ")
            )?;
        }
    }

    let wg_size = config.wgsl_workgroup_size.max(1);
    if config.is_tiled() {
        let tile_elems = (config.tile_m * config.tile_k).max(1);
        writeln!(out, "var<workgroup> wg_tile_a: array<f32, {tile_elems}>;")?;
        writeln!(out, "var<workgroup> wg_tile_b: array<f32, {tile_elems}>;")?;
    }
    writeln!(out, "\n@compute @workgroup_size({wg_size})")?;
    writeln!(
        out,
        "fn main(@builtin(global_invocation_id) gid: vec3<u32>) {{"
    )?;
    writeln!(out, "    let idx = gid.x;")?;
    writeln!(out, "    if (idx >= arrayLength(&output_0)) {{ return; }}")?;

    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("stablehlo", "constant") {
            continue;
        }
        if op.is_op("func", "return") {
            if let Some(&ret_val) = op.operands.first() {
                let r_name = value_ident(module, ret_val, &mut names, &mut counter);
                writeln!(out, "    output_0[idx] = {r_name}[idx];")?;
            }
            continue;
        }

        let Some(&res_val) = op.results.first() else {
            continue;
        };
        let res_name = value_ident(module, res_val, &mut names, &mut counter);
        let res_len = tensor_len(module, res_val);

        if op.is_op("stablehlo", "uniform_dequantize") {
            let src_val = op.operands[0];
            let src_name = value_ident(module, src_val, &mut names, &mut counter);
            let (scale, zp) = match module.values[src_val].ty.as_tensor().map(|t| &t.dtype) {
                Some(DType::QuantUniform {
                    scale, zero_point, ..
                }) => (scale.parse::<f32>().unwrap_or(1.0), *zero_point),
                _ => (1.0, 0),
            };
            writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
            writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
            writeln!(
                out,
                "        {res_name}[i] = f32({src_name}[i] - {zp}i) * {scale:.6};"
            )?;
            writeln!(out, "    }}")?;
            continue;
        }

        if op.is_op("func", "call") {
            let callee = match op.attributes.get("callee") {
                Some(Attribute::SymbolRef(s)) | Some(Attribute::String(s)) => {
                    s.trim_start_matches('@').to_string()
                }
                _ => "outlined_fn".to_string(),
            };
            writeln!(
                out,
                "    // func.call @{callee} ({} args)",
                op.operands.len()
            )?;
            writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
            if let Some(&arg0) = op.operands.first() {
                let a = value_ident(module, arg0, &mut names, &mut counter);
                let a_len = tensor_len(module, arg0).max(1);
                writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                writeln!(out, "        {res_name}[i] = {a}[i % {a_len}u];")?;
                writeln!(out, "    }}")?;
            }
            continue;
        }

        if let Some(hlo) = StableHloOp::from_op(op) {
            match hlo {
                StableHloOp::Add { lhs, rhs, .. }
                | StableHloOp::Subtract { lhs, rhs, .. }
                | StableHloOp::Multiply { lhs, rhs, .. }
                | StableHloOp::Divide { lhs, rhs, .. }
                | StableHloOp::Maximum { lhs, rhs, .. }
                | StableHloOp::Minimum { lhs, rhs, .. }
                | StableHloOp::Power { lhs, rhs, .. } => {
                    let a_name = value_ident(module, lhs, &mut names, &mut counter);
                    let b_name = value_ident(module, rhs, &mut names, &mut counter);
                    let a = wgsl_idx(module, lhs, res_len, &a_name, "i");
                    let b = wgsl_idx(module, rhs, res_len, &b_name, "i");
                    let expr = match op.name.name.as_str() {
                        "add" => format!("{a} + {b}"),
                        "subtract" => format!("{a} - {b}"),
                        "multiply" => format!("{a} * {b}"),
                        "divide" => format!("{a} / {b}"),
                        "maximum" => format!("max({a}, {b})"),
                        "power" => format!("pow({a}, {b})"),
                        _ => format!("min({a}, {b})"),
                    };
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(out, "        {res_name}[i] = {expr};")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Exp { operand, .. }
                | StableHloOp::Log { operand, .. }
                | StableHloOp::Tanh { operand, .. }
                | StableHloOp::Sqrt { operand, .. }
                | StableHloOp::Rsqrt { operand, .. }
                | StableHloOp::Sine { operand, .. }
                | StableHloOp::Cosine { operand, .. }
                | StableHloOp::Abs { operand, .. }
                | StableHloOp::Negate { operand, .. }
                | StableHloOp::Logistic { operand, .. }
                | StableHloOp::Convert { operand, .. }
                | StableHloOp::Reshape { operand, .. } => {
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let expr = match op.name.name.as_str() {
                        "exponential" => format!("exp({x}[i])"),
                        "log" => format!("log({x}[i])"),
                        "tanh" => format!("tanh({x}[i])"),
                        "sqrt" => format!("sqrt({x}[i])"),
                        "rsqrt" => format!("inverseSqrt({x}[i])"),
                        "sine" => format!("sin({x}[i])"),
                        "cosine" => format!("cos({x}[i])"),
                        "abs" => format!("abs({x}[i])"),
                        "negate" => format!("-{x}[i]"),
                        "logistic" => format!("1.0 / (1.0 + exp(-{x}[i]))"),
                        _ => format!("{x}[i]"),
                    };
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(out, "        {res_name}[i] = {expr};")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Clamp {
                    min, operand, max, ..
                } => {
                    let lo = value_ident(module, min, &mut names, &mut counter);
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let hi = value_ident(module, max, &mut names, &mut counter);
                    let lo_len = tensor_len(module, min).max(1);
                    let hi_len = tensor_len(module, max).max(1);
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(
                        out,
                        "        {res_name}[i] = clamp({x}[i], {lo}[i % {lo_len}u], \
                         {hi}[i % {hi_len}u]);"
                    )?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::BroadcastInDim { operand, .. }
                | StableHloOp::Transpose { operand, .. }
                | StableHloOp::Slice { operand, .. }
                | StableHloOp::DynamicSlice { operand, .. }
                | StableHloOp::Pad { operand, .. } => {
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let x_len = tensor_len(module, operand).max(1);
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(out, "        {res_name}[i] = {x}[i % {x_len}u];")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Concatenate { inputs, .. } => {
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    let mut offset = 0usize;
                    for &inp in &inputs {
                        let a = value_ident(module, inp, &mut names, &mut counter);
                        let a_len = tensor_len(module, inp);
                        writeln!(out, "    for (var i = 0u; i < {a_len}u; i = i + 1u) {{")?;
                        writeln!(out, "        {res_name}[{offset}u + i] = {a}[i];")?;
                        writeln!(out, "    }}")?;
                        offset += a_len;
                    }
                }
                StableHloOp::Reduce {
                    inputs,
                    init_values,
                    reducer_op,
                    ..
                } if !inputs.is_empty() => {
                    let operand = inputs[0];
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let init_expr = init_values
                        .first()
                        .map(|&v| {
                            let n = value_ident(module, v, &mut names, &mut counter);
                            format!("{n}[0u]")
                        })
                        .unwrap_or_else(|| "0.0".to_string());
                    let x_len = tensor_len(module, operand);
                    let red_ext = (x_len / res_len.max(1)).max(1);
                    let elem = format!("{x}[r * {red_ext}u + c]");
                    let red_op = reducer_op.as_deref().unwrap_or("add");
                    let step_expr = if red_op.contains("maximum") {
                        format!("max(acc, {elem})")
                    } else if red_op.contains("minimum") {
                        format!("min(acc, {elem})")
                    } else if red_op.contains("multiply") {
                        format!("acc * {elem}")
                    } else {
                        format!("acc + {elem}")
                    };
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var r = 0u; r < {res_len}u; r = r + 1u) {{")?;
                    writeln!(out, "        var acc: f32 = {init_expr};")?;
                    writeln!(
                        out,
                        "        for (var c = 0u; c < {red_ext}u; c = c + 1u) {{"
                    )?;
                    writeln!(out, "            acc = {step_expr};")?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "        {res_name}[r] = acc;")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Gather {
                    operand,
                    start_indices,
                    ..
                } => {
                    let tbl = value_ident(module, operand, &mut names, &mut counter);
                    let idx_v = value_ident(module, start_indices, &mut names, &mut counter);
                    let n_idx = tensor_len(module, start_indices).max(1);
                    let cols = (res_len / n_idx).max(1);
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var r = 0u; r < {n_idx}u; r = r + 1u) {{")?;
                    writeln!(out, "        let row = u32({idx_v}[r]);")?;
                    writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
                    writeln!(
                        out,
                        "            {res_name}[r * {cols}u + c] = {tbl}[row * {cols}u + c];"
                    )?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Scatter {
                    operand,
                    scatter_indices,
                    updates,
                    ..
                } => {
                    let base = value_ident(module, operand, &mut names, &mut counter);
                    let idx_v = value_ident(module, scatter_indices, &mut names, &mut counter);
                    let upd = value_ident(module, updates, &mut names, &mut counter);
                    let n_idx = tensor_len(module, scatter_indices).max(1);
                    let upd_len = tensor_len(module, updates);
                    let cols = (upd_len / n_idx).max(1);
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(out, "        {res_name}[i] = {base}[i];")?;
                    writeln!(out, "    }}")?;
                    writeln!(out, "    for (var r = 0u; r < {n_idx}u; r = r + 1u) {{")?;
                    writeln!(out, "        let row = u32({idx_v}[r]);")?;
                    writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
                    writeln!(
                        out,
                        "            {res_name}[row * {cols}u + c] = {upd}[r * {cols}u + c];"
                    )?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::DotGeneral {
                    lhs,
                    rhs,
                    dimension_numbers: dims,
                    ..
                } => {
                    let packed = dims.rhs_contracting_dimensions == [1];
                    let a = value_ident(module, lhs, &mut names, &mut counter);
                    let b = value_ident(module, rhs, &mut names, &mut counter);
                    let lhs_dims = module.values[lhs]
                        .ty
                        .as_tensor()
                        .map(tensor_shape_dims)
                        .unwrap_or_else(|| vec![1, 1]);
                    let rhs_dims = module.values[rhs]
                        .ty
                        .as_tensor()
                        .map(tensor_shape_dims)
                        .unwrap_or_else(|| vec![1, 1]);
                    let m = *lhs_dims.first().unwrap_or(&1);
                    let k = *lhs_dims.get(1).unwrap_or(&1);
                    let n = if packed {
                        *rhs_dims.first().unwrap_or(&1)
                    } else {
                        *rhs_dims.get(1).unwrap_or(&1)
                    };
                    let b_idx = if packed {
                        format!("n * {k}u + k")
                    } else {
                        format!("k * {n}u + n")
                    };
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var m = 0u; m < {m}u; m = m + 1u) {{")?;
                    writeln!(out, "        for (var n = 0u; n < {n}u; n = n + 1u) {{")?;
                    writeln!(out, "            var acc: f32 = 0.0;")?;
                    writeln!(out, "            for (var k = 0u; k < {k}u; k = k + 1u) {{")?;
                    writeln!(
                        out,
                        "                acc = acc + {a}[m * {k}u + k] * {b}[{b_idx}];"
                    )?;
                    writeln!(out, "            }}")?;
                    writeln!(out, "            {res_name}[m * {n}u + n] = acc;")?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Composite { name, inputs, .. } => {
                    emit_wgsl_composite(
                        module,
                        op,
                        &name,
                        &inputs,
                        res_val,
                        &res_name,
                        res_len,
                        &mut names,
                        &mut counter,
                        out,
                    )?;
                }
                _ => {
                    let a = op
                        .operands
                        .first()
                        .map(|&v| value_ident(module, v, &mut names, &mut counter))
                        .unwrap_or_else(|| "input_0".to_string());
                    writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
                    writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
                    writeln!(out, "        {res_name}[i] = {a}[i];")?;
                    writeln!(out, "    }}")?;
                }
            }
        } else if op.name.dialect == "castforge" {
            let full_name = format!("castforge.{}", op.name.name);
            let inputs: Vec<ValueId> = op.operands.to_vec();
            emit_wgsl_composite(
                module,
                op,
                &full_name,
                &inputs,
                res_val,
                &res_name,
                res_len,
                &mut names,
                &mut counter,
                out,
            )?;
        }
    }

    writeln!(out, "}}")?;
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_wgsl_composite(
    module: &Module,
    op: &Operation,
    name: &str,
    inputs: &[ValueId],
    res_val: ValueId,
    res_name: &str,
    res_len: usize,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
    out: &mut String,
) -> Result<()> {
    if name == "castforge.fused_add_max" && inputs.len() == 3 {
        let a_n = value_ident(module, inputs[0], names, counter);
        let b_n = value_ident(module, inputs[1], names, counter);
        let c_n = value_ident(module, inputs[2], names, counter);
        let a = wgsl_idx(module, inputs[0], res_len, &a_n, "i");
        let b = wgsl_idx(module, inputs[1], res_len, &b_n, "i");
        let c = wgsl_idx(module, inputs[2], res_len, &c_n, "i");
        writeln!(
            out,
            "    // Lowered from stablehlo.composite (castforge.fused_add_max)"
        )?;
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(out, "        {res_name}[i] = max({a} + {b}, {c});")?;
        writeln!(out, "    }}")?;
    } else if name == "castforge.fma" && inputs.len() >= 3 {
        let a_n = value_ident(module, inputs[0], names, counter);
        let b_n = value_ident(module, inputs[1], names, counter);
        let c_n = value_ident(module, inputs[2], names, counter);
        let a = wgsl_idx(module, inputs[0], res_len, &a_n, "i");
        let b = wgsl_idx(module, inputs[1], res_len, &b_n, "i");
        let c = wgsl_idx(module, inputs[2], res_len, &c_n, "i");
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(out, "        {res_name}[i] = fma({a}, {b}, {c});")?;
        writeln!(out, "    }}")?;
    } else if name == "castforge.fused_matmul_epilogue" && inputs.len() >= 3 {
        let packed = op
            .attributes
            .get("packed_rhs")
            .is_some_and(|a| matches!(a, Attribute::Bool(true)));
        let epilogue = op
            .attributes
            .get("epilogue")
            .or_else(|| op.attributes.get("activation"))
            .and_then(|a| a.as_str())
            .unwrap_or("bias_relu");
        let a = value_ident(module, inputs[0], names, counter);
        let b = value_ident(module, inputs[1], names, counter);
        let bias = value_ident(module, inputs[2], names, counter);
        let bias_expr = wgsl_idx(module, inputs[2], res_len, &bias, "flat");
        let lhs_dims = module.values[inputs[0]]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, 1]);
        let rhs_dims = module.values[inputs[1]]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, 1]);
        let m = *lhs_dims.first().unwrap_or(&1);
        let k = *lhs_dims.get(1).unwrap_or(&1);
        let n = if packed {
            *rhs_dims.first().unwrap_or(&1)
        } else {
            *rhs_dims.get(1).unwrap_or(&1)
        };
        let b_idx = if packed {
            format!("n * {k}u + k")
        } else {
            format!("k * {n}u + n")
        };
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var m = 0u; m < {m}u; m = m + 1u) {{")?;
        writeln!(out, "        for (var n = 0u; n < {n}u; n = n + 1u) {{")?;
        writeln!(out, "            var acc: f32 = 0.0;")?;
        writeln!(out, "            for (var k = 0u; k < {k}u; k = k + 1u) {{")?;
        writeln!(
            out,
            "                acc = acc + {a}[m * {k}u + k] * {b}[{b_idx}];"
        )?;
        writeln!(out, "            }}")?;
        writeln!(out, "            let flat = m * {n}u + n;")?;
        writeln!(out, "            let val = acc + {bias_expr};")?;
        match epilogue {
            "bias_relu" | "relu" => {
                if let Some(&z_id) = inputs.get(3) {
                    let z_n = value_ident(module, z_id, names, counter);
                    let z = wgsl_idx(module, z_id, res_len, &z_n, "flat");
                    writeln!(out, "            {res_name}[flat] = max(val, {z});")?;
                } else {
                    writeln!(out, "            {res_name}[flat] = max(val, 0.0);")?;
                }
            }
            "bias_tanh" | "tanh" => {
                writeln!(out, "            {res_name}[flat] = tanh(val);")?;
            }
            "bias_silu" | "silu" => {
                writeln!(
                    out,
                    "            {res_name}[flat] = val / (1.0 + exp(-val));"
                )?;
            }
            "bias_gelu" | "gelu" => {
                writeln!(
                    out,
                    "            {res_name}[flat] = 0.5 * val * \
                     (1.0 + tanh(0.7978846 * (val + 0.044715 * val * val * val)));"
                )?;
            }
            "bias_scale" if inputs.len() >= 4 => {
                let s_n = value_ident(module, inputs[3], names, counter);
                let s = wgsl_idx(module, inputs[3], res_len, &s_n, "flat");
                writeln!(out, "            {res_name}[flat] = val * {s};")?;
            }
            _ => {
                writeln!(out, "            {res_name}[flat] = val;")?;
            }
        }
        writeln!(out, "        }}")?;
        writeln!(out, "    }}")?;
    } else if matches!(name, "castforge.fused_swiglu" | "castforge.fused_gated_mlp")
        && inputs.len() >= 2
    {
        let g = value_ident(module, inputs[0], names, counter);
        let u = value_ident(module, inputs[1], names, counter);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(
            out,
            "        {res_name}[i] = ({g}[i] / (1.0 + exp(-{g}[i]))) * {u}[i];"
        )?;
        writeln!(out, "    }}")?;
    } else if matches!(
        name,
        "castforge.fused_rmsnorm"
            | "castforge.fused_layernorm"
            | "castforge.fused_residual_rmsnorm"
    ) && !inputs.is_empty()
    {
        let x = value_ident(module, inputs[0], names, counter);
        let dims = module.values[res_val]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, res_len]);
        let cols = (*dims.last().unwrap_or(&res_len)).max(1);
        let rows = (res_len / cols).max(1);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var r = 0u; r < {rows}u; r = r + 1u) {{")?;
        writeln!(out, "        var sq: f32 = 0.0;")?;
        writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
        writeln!(out, "            let v = {x}[r * {cols}u + c];")?;
        writeln!(out, "            sq = sq + v * v;")?;
        writeln!(out, "        }}")?;
        writeln!(
            out,
            "        let inv_rms = inverseSqrt(sq / f32({cols}u) + 1e-5);"
        )?;
        writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
        if let Some(&w_id) = inputs.last()
            && inputs.len() >= 2
        {
            let w = value_ident(module, w_id, names, counter);
            let w_len = tensor_len(module, w_id).max(1);
            writeln!(
                out,
                "            {res_name}[r * {cols}u + c] = \
                 {x}[r * {cols}u + c] * inv_rms * {w}[c % {w_len}u];"
            )?;
        } else {
            writeln!(
                out,
                "            {res_name}[r * {cols}u + c] = {x}[r * {cols}u + c] * inv_rms;"
            )?;
        }
        writeln!(out, "        }}")?;
        writeln!(out, "    }}")?;
    } else if matches!(
        name,
        "castforge.fused_softmax" | "castforge.fused_log_softmax"
    ) && !inputs.is_empty()
    {
        let x = value_ident(module, inputs[0], names, counter);
        let dims = module.values[res_val]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, res_len]);
        let cols = (*dims.last().unwrap_or(&res_len)).max(1);
        let rows = (res_len / cols).max(1);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var r = 0u; r < {rows}u; r = r + 1u) {{")?;
        writeln!(out, "        var max_v: f32 = {x}[r * {cols}u];")?;
        writeln!(out, "        for (var c = 1u; c < {cols}u; c = c + 1u) {{")?;
        writeln!(out, "            max_v = max(max_v, {x}[r * {cols}u + c]);")?;
        writeln!(out, "        }}")?;
        writeln!(out, "        var sum_exp: f32 = 0.0;")?;
        writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
        writeln!(
            out,
            "            sum_exp = sum_exp + exp({x}[r * {cols}u + c] - max_v);"
        )?;
        writeln!(out, "        }}")?;
        if name == "castforge.fused_log_softmax" {
            writeln!(out, "        let lse: f32 = max_v + log(sum_exp);")?;
            writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
            writeln!(
                out,
                "            {res_name}[r * {cols}u + c] = {x}[r * {cols}u + c] - lse;"
            )?;
            writeln!(out, "        }}")?;
        } else {
            writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
            writeln!(
                out,
                "            {res_name}[r * {cols}u + c] = \
                 exp({x}[r * {cols}u + c] - max_v) / sum_exp;"
            )?;
            writeln!(out, "        }}")?;
        }
        writeln!(out, "    }}")?;
    } else if matches!(
        name,
        "castforge.fused_attention" | "castforge.flash_attention"
    ) && inputs.len() >= 3
    {
        let q = value_ident(module, inputs[0], names, counter);
        let k = value_ident(module, inputs[1], names, counter);
        let v = value_ident(module, inputs[2], names, counter);
        let dims = module.values[res_val]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, res_len]);
        let d_head = (*dims.last().unwrap_or(&1)).max(1);
        let seq = (res_len / d_head).max(1);
        let scale = 1.0f32 / (d_head as f32).sqrt();
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var qi = 0u; qi < {seq}u; qi = qi + 1u) {{")?;
        writeln!(
            out,
            "        for (var d = 0u; d < {d_head}u; d = d + 1u) {{"
        )?;
        writeln!(out, "            var acc: f32 = 0.0;")?;
        writeln!(
            out,
            "            for (var kj = 0u; kj < {seq}u; kj = kj + 1u) {{"
        )?;
        writeln!(
            out,
            "                acc = acc + ({q}[qi * {d_head}u + d] * \
             {k}[kj * {d_head}u + d] * {scale:.6}) * {v}[kj * {d_head}u + d];"
        )?;
        writeln!(out, "            }}")?;
        writeln!(out, "            {res_name}[qi * {d_head}u + d] = acc;")?;
        writeln!(out, "        }}")?;
        writeln!(out, "    }}")?;
    } else if name == "castforge.fused_rope" && inputs.len() >= 3 {
        let x = value_ident(module, inputs[0], names, counter);
        let c_arr = value_ident(module, inputs[1], names, counter);
        let s_arr = value_ident(module, inputs[2], names, counter);
        let dims = module.values[res_val]
            .ty
            .as_tensor()
            .map(tensor_shape_dims)
            .unwrap_or_else(|| vec![1, res_len]);
        let cols = *dims.last().unwrap_or(&res_len).max(&2);
        let rows = (res_len / cols).max(1);
        let half = cols / 2;
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var r = 0u; r < {rows}u; r = r + 1u) {{")?;
        writeln!(out, "        for (var c = 0u; c < {cols}u; c = c + 1u) {{")?;
        writeln!(out, "            let idx = r * {cols}u + c;")?;
        writeln!(
            out,
            "            let rot = select(\
             {x}[idx - {half}u], -{x}[idx + {half}u], c < {half}u);"
        )?;
        writeln!(
            out,
            "            {res_name}[idx] = \
             {x}[idx] * {c_arr}[idx] + rot * {s_arr}[idx];"
        )?;
        writeln!(out, "        }}")?;
        writeln!(out, "    }}")?;
    } else if name == "castforge.fused_gelu" && !inputs.is_empty() {
        let x = value_ident(module, inputs[0], names, counter);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(out, "        let v = {x}[i];")?;
        writeln!(
            out,
            "        {res_name}[i] = 0.5 * v * \
             (1.0 + tanh(0.7978846 * (v + 0.044715 * v * v * v)));"
        )?;
        writeln!(out, "    }}")?;
    } else if name == "castforge.fused_geglu" && inputs.len() >= 2 {
        let g = value_ident(module, inputs[0], names, counter);
        let u = value_ident(module, inputs[1], names, counter);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(out, "        let v = {g}[i];")?;
        writeln!(
            out,
            "        let gv = 0.5 * v * \
             (1.0 + tanh(0.7978846 * (v + 0.044715 * v * v * v)));"
        )?;
        writeln!(out, "        {res_name}[i] = gv * {u}[i];")?;
        writeln!(out, "    }}")?;
    } else if let Some(&first_in) = inputs.first() {
        let a = value_ident(module, first_in, names, counter);
        writeln!(out, "    var {res_name}: array<f32, {res_len}>;")?;
        writeln!(out, "    for (var i = 0u; i < {res_len}u; i = i + 1u) {{")?;
        writeln!(out, "        {res_name}[i] = {a}[i];")?;
        writeln!(out, "    }}")?;
    }
    Ok(())
}
