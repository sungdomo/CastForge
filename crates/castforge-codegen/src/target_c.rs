use crate::{
    MemoryPlan, TargetConfig, build_memory_plan, sanitize_ident, tensor_len, tensor_shape_dims,
    value_ident,
};
use anyhow::{Result, anyhow};
use castforge_dialect_stablehlo::StableHloOp;
use castforge_ir::{DType, Module, OpId, ValueId};
use std::collections::HashMap;
use std::fmt::Write;

/// Portable C99 Code Generator (`CodegenTarget::C`)
pub fn emit_c_module(module: &Module) -> Result<String> {
    emit_c_module_with_config(module, &TargetConfig::default())
}

/// Portable C99 Code Generator parameterized by `TargetConfig`.
pub fn emit_c_module_with_config(module: &Module, config: &TargetConfig) -> Result<String> {
    let mut out = String::new();
    let plan = build_memory_plan(module);
    writeln!(
        out,
        "/* Auto-generated by CastForge Codegen (Target: C99) */"
    )?;
    writeln!(
        out,
        "/* Constant Weights: {} B | Activation Workspace: {} B \
         (Naive: {} B, Saved: {} B across {} arena slots) */",
        plan.total_constant_bytes,
        plan.total_activation_bytes,
        plan.naive_activation_bytes,
        plan.saved_activation_bytes(),
        plan.reusable_slot_count
    )?;
    if config.is_tiled() {
        writeln!(
            out,
            "/* Hardware Config: Tiled GEMM ({}x{}x{}), SIMD Width: {} lanes */",
            config.tile_m, config.tile_n, config.tile_k, config.simd_width
        )?;
    }
    writeln!(out, "#include <stdint.h>\n#include <math.h>\n")?;

    for fn_op_id in module.functions() {
        emit_c_func(module, fn_op_id, &plan, config, &mut out)?;
    }

    Ok(out)
}

fn emit_c_func(
    module: &Module,
    fn_op_id: OpId,
    plan: &MemoryPlan,
    config: &TargetConfig,
    out: &mut String,
) -> Result<()> {
    let fn_op = &module.ops[fn_op_id];
    let fn_name = sanitize_ident(
        fn_op
            .attributes
            .get("sym_name")
            .and_then(|a| a.as_str())
            .unwrap_or("forward"),
    );
    let region_id = fn_op.regions[0];
    let block_id = module.regions[region_id].blocks[0];
    let block = &module.blocks[block_id];

    let mut names: HashMap<ValueId, String> = HashMap::new();
    let mut counter = 0usize;

    let mut params = Vec::new();
    for &arg_id in &block.arguments {
        let name = value_ident(module, arg_id, &mut names, &mut counter);
        params.push(format!("const float* restrict {name}"));
    }
    params.push("float* restrict out_buf".to_string());

    writeln!(out, "void {fn_name}({}) {{", params.join(", "))?;

    let arena_elems = plan.arena_f32_len();
    if arena_elems > 0 {
        writeln!(
            out,
            "    float arena[{arena_elems}]; /* {} B shared activation workspace */",
            plan.arena_workspace_bytes
        )?;
    }

    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("func", "return") {
            if let Some(&ret_val) = op.operands.first() {
                let r_name = value_ident(module, ret_val, &mut names, &mut counter);
                let r_len = tensor_len(module, ret_val);
                writeln!(
                    out,
                    "    for (int i = 0; i < {r_len}; ++i) out_buf[i] = {r_name}[i];"
                )?;
            }
            continue;
        }
        let Some(&res_val) = op.results.first() else {
            continue;
        };
        let res_name = value_ident(module, res_val, &mut names, &mut counter);
        let res_len = tensor_len(module, res_val);

        if op.is_op("stablehlo", "constant") {
            let t_ty = module.values[res_val]
                .ty
                .as_tensor()
                .ok_or_else(|| anyhow!("constant without tensor type"))?;
            let val_attr = op.attributes.get("value");
            if let DType::QuantUniform { .. } = &t_ty.dtype {
                let q_vals = val_attr
                    .and_then(|a| module.tensor_store.resolve_i8_attr(a, res_len))
                    .unwrap_or_else(|| vec![0; res_len]);
                let elems: Vec<String> = q_vals.iter().map(|v| v.to_string()).collect();
                writeln!(
                    out,
                    "    static const int8_t {res_name}[{res_len}] = {{ {} }};",
                    elems.join(", ")
                )?;
            } else {
                let vals = val_attr
                    .and_then(|a| module.tensor_store.resolve_f32_attr(a, res_len))
                    .unwrap_or_else(|| vec![0.0; res_len]);
                let elems: Vec<String> = vals.iter().map(|v| format!("{v:.6}f")).collect();
                writeln!(
                    out,
                    "    static const float {res_name}[{res_len}] = {{ {} }};",
                    elems.join(", ")
                )?;
            }
            continue;
        }

        if let Some(alloc) = plan.allocation_for(res_val) {
            if let (Some(slot), Some(off)) = (alloc.arena_slot, alloc.arena_offset) {
                let elem_off = off / 4;
                writeln!(
                    out,
                    "    /* [arena] {res_name}: slot #{slot} @ offset {off} B \
                     (live steps {}..={}) */",
                    alloc.first_def, alloc.last_use
                )?;
                writeln!(out, "    float* const {res_name} = &arena[{elem_off}];")?;
            } else {
                writeln!(out, "    float {res_name}[{res_len}];")?;
            }
        } else {
            writeln!(out, "    float {res_name}[{res_len}];")?;
        }

        if op.is_op("stablehlo", "uniform_dequantize") {
            let src_val = op.operands[0];
            let src_name = value_ident(module, src_val, &mut names, &mut counter);
            let (scale, zp) = match module.values[src_val].ty.as_tensor().map(|t| &t.dtype) {
                Some(DType::QuantUniform {
                    scale, zero_point, ..
                }) => (scale.parse::<f32>().unwrap_or(1.0), *zero_point),
                _ => (1.0, 0),
            };
            writeln!(out, "    for (int i = 0; i < {res_len}; ++i) {{")?;
            writeln!(
                out,
                "        {res_name}[i] = ((float)((int32_t){src_name}[i] - {zp})) * {scale:.6}f;"
            )?;
            writeln!(out, "    }}")?;
            continue;
        }

        emit_c_hlo_op(
            module,
            config,
            op_id,
            &res_name,
            res_len,
            &mut names,
            &mut counter,
            out,
        )?;
    }
    writeln!(out, "}}")?;
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_c_hlo_op(
    module: &Module,
    config: &TargetConfig,
    op_id: OpId,
    res_name: &str,
    res_len: usize,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
    out: &mut String,
) -> Result<()> {
    let op = &module.ops[op_id];
    let Some(hlo) = StableHloOp::from_op(op) else {
        return Ok(());
    };

    match hlo {
        StableHloOp::Add { lhs, rhs, .. }
        | StableHloOp::Subtract { lhs, rhs, .. }
        | StableHloOp::Multiply { lhs, rhs, .. }
        | StableHloOp::Divide { lhs, rhs, .. }
        | StableHloOp::Maximum { lhs, rhs, .. }
        | StableHloOp::Minimum { lhs, rhs, .. } => {
            let a = value_ident(module, lhs, names, counter);
            let b = value_ident(module, rhs, names, counter);
            let expr = match op.name.name.as_str() {
                "add" => format!("{a}[i] + {b}[i]"),
                "subtract" => format!("{a}[i] - {b}[i]"),
                "multiply" => format!("{a}[i] * {b}[i]"),
                "divide" => format!("{a}[i] / {b}[i]"),
                "maximum" => format!("fmaxf({a}[i], {b}[i])"),
                _ => format!("fminf({a}[i], {b}[i])"),
            };
            writeln!(
                out,
                "    for (int i = 0; i < {res_len}; ++i) {res_name}[i] = {expr};"
            )?;
        }
        StableHloOp::Exp { operand, .. }
        | StableHloOp::Tanh { operand, .. }
        | StableHloOp::Rsqrt { operand, .. }
        | StableHloOp::Convert { operand, .. }
        | StableHloOp::Reshape { operand, .. } => {
            let x = value_ident(module, operand, names, counter);
            let expr = match op.name.name.as_str() {
                "exponential" => format!("expf({x}[i])"),
                "tanh" => format!("tanhf({x}[i])"),
                "rsqrt" => format!("1.0f / sqrtf({x}[i])"),
                _ => format!("{x}[i]"),
            };
            writeln!(
                out,
                "    for (int i = 0; i < {res_len}; ++i) {res_name}[i] = {expr};"
            )?;
        }
        StableHloOp::Transpose {
            operand,
            permutation,
            ..
        } => {
            let x = value_ident(module, operand, names, counter);
            let in_dims = module.values[operand]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![res_len]);
            if in_dims.len() == 2 && permutation == vec![1, 0] {
                let (r, c) = (in_dims[0], in_dims[1]);
                writeln!(out, "    for (int r = 0; r < {r}; ++r) {{")?;
                writeln!(
                    out,
                    "        for (int c = 0; c < {c}; ++c) \
                     {res_name}[c * {r} + r] = {x}[r * {c} + c];"
                )?;
                writeln!(out, "    }}")?;
            } else {
                writeln!(
                    out,
                    "    for (int i = 0; i < {res_len}; ++i) {res_name}[i] = {x}[i];"
                )?;
            }
        }
        StableHloOp::BroadcastInDim { operand, .. } => {
            let x = value_ident(module, operand, names, counter);
            let in_len = tensor_len(module, operand).max(1);
            let stride = (res_len / in_len).max(1);
            writeln!(
                out,
                "    for (int i = 0; i < {res_len}; ++i) \
                 {res_name}[i] = {x}[(i / {stride}) % {in_len}];"
            )?;
        }
        StableHloOp::Reduce {
            inputs,
            init_values,
            ..
        } => {
            let inp = value_ident(module, inputs[0], names, counter);
            let init = value_ident(module, init_values[0], names, counter);
            let in_len = tensor_len(module, inputs[0]);
            let inner = (in_len / res_len.max(1)).max(1);
            writeln!(out, "    for (int o = 0; o < {res_len}; ++o) {{")?;
            writeln!(out, "        float acc = {init}[0];")?;
            writeln!(
                out,
                "        for (int k = 0; k < {inner}; ++k) \
                 acc += {inp}[o * {inner} + k];"
            )?;
            writeln!(out, "        {res_name}[o] = acc;")?;
            writeln!(out, "    }}")?;
        }
        StableHloOp::DotGeneral {
            lhs,
            rhs,
            dimension_numbers: dims,
            ..
        } => {
            let packed = dims.rhs_contracting_dimensions == [1];
            let a = value_ident(module, lhs, names, counter);
            let b = value_ident(module, rhs, names, counter);
            let lhs_dims = module.values[lhs]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![1, 1]);
            let rhs_dims = module.values[rhs]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![1, 1]);
            let m = *lhs_dims.first().unwrap_or(&1);
            let k = *lhs_dims.get(1).unwrap_or(&1);
            let n = if packed {
                *rhs_dims.first().unwrap_or(&1)
            } else {
                *rhs_dims.get(1).unwrap_or(&1)
            };
            let b_idx = if packed {
                format!("n * {k} + k")
            } else {
                format!("k * {n} + n")
            };
            if config.is_tiled() {
                let (tm, tn, tk) = (config.tile_m, config.tile_n, config.tile_k);
                writeln!(out, "    for (int m0 = 0; m0 < {m}; m0 += {tm}) {{")?;
                writeln!(out, "        for (int n0 = 0; n0 < {n}; n0 += {tn}) {{")?;
                writeln!(
                    out,
                    "            for (int m = m0; m < m0 + {tm} && m < {m}; ++m) {{"
                )?;
                writeln!(
                    out,
                    "                for (int n = n0; n < n0 + {tn} && n < {n}; ++n) {{"
                )?;
                writeln!(out, "                    float acc = 0.0f;")?;
                writeln!(
                    out,
                    "                    for (int k0 = 0; k0 < {k}; k0 += {tk}) {{"
                )?;
                writeln!(
                    out,
                    "                        for (int k = k0; k < k0 + {tk} && k < {k}; ++k) \
                     acc += {a}[m * {k} + k] * {b}[{b_idx}];"
                )?;
                writeln!(out, "                    }}")?;
                writeln!(out, "                    {res_name}[m * {n} + n] = acc;")?;
                writeln!(out, "                }}")?;
                writeln!(out, "            }}")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else {
                writeln!(out, "    for (int m = 0; m < {m}; ++m) {{")?;
                writeln!(out, "        for (int n = 0; n < {n}; ++n) {{")?;
                writeln!(out, "            float acc = 0.0f;")?;
                writeln!(
                    out,
                    "            for (int k = 0; k < {k}; ++k) \
                     acc += {a}[m * {k} + k] * {b}[{b_idx}];"
                )?;
                writeln!(out, "            {res_name}[m * {n} + n] = acc;")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            }
        }
        StableHloOp::Composite { name, inputs, .. } => {
            if name == "castforge.fused_add_max" && inputs.len() == 3 {
                let a = value_ident(module, inputs[0], names, counter);
                let b = value_ident(module, inputs[1], names, counter);
                let c = value_ident(module, inputs[2], names, counter);
                writeln!(
                    out,
                    "    for (int i = 0; i < {res_len}; ++i) \
                     {res_name}[i] = fmaxf({a}[i] + {b}[i], {c}[i]);"
                )?;
            } else if name == "castforge.fused_matmul_epilogue" && inputs.len() >= 3 {
                let packed = op
                    .attributes
                    .get("packed_rhs")
                    .is_some_and(|a| matches!(a, castforge_ir::Attribute::Bool(true)));
                let a = value_ident(module, inputs[0], names, counter);
                let b = value_ident(module, inputs[1], names, counter);
                let bias = value_ident(module, inputs[2], names, counter);
                let lhs_dims = module.values[inputs[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let rhs_dims = module.values[inputs[1]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let m = *lhs_dims.first().unwrap_or(&1);
                let k = *lhs_dims.get(1).unwrap_or(&1);
                let n = if packed {
                    *rhs_dims.first().unwrap_or(&1)
                } else {
                    *rhs_dims.get(1).unwrap_or(&1)
                };
                let b_idx = if packed {
                    format!("n * {k} + k")
                } else {
                    format!("k * {n} + n")
                };
                let epilogue = op
                    .attributes
                    .get("epilogue")
                    .and_then(|attr| attr.as_str())
                    .unwrap_or("bias");
                writeln!(out, "    for (int m = 0; m < {m}; ++m) {{")?;
                writeln!(out, "        for (int n = 0; n < {n}; ++n) {{")?;
                writeln!(out, "            float acc = 0.0f;")?;
                writeln!(
                    out,
                    "            for (int k = 0; k < {k}; ++k) \
                     acc += {a}[m * {k} + k] * {b}[{b_idx}];"
                )?;
                writeln!(out, "            int idx = m * {n} + n;")?;
                writeln!(out, "            float val = acc + {bias}[idx];")?;
                match epilogue {
                    "bias_relu" if inputs.len() >= 4 => {
                        let z = value_ident(module, inputs[3], names, counter);
                        writeln!(out, "            {res_name}[idx] = fmaxf(val, {z}[idx]);")?;
                    }
                    "bias_tanh" => {
                        writeln!(out, "            {res_name}[idx] = tanhf(val);")?;
                    }
                    "bias_silu" => {
                        writeln!(
                            out,
                            "            {res_name}[idx] = val / (1.0f + expf(-val));"
                        )?;
                    }
                    "bias_scale" if inputs.len() >= 4 => {
                        let s = value_ident(module, inputs[3], names, counter);
                        writeln!(out, "            {res_name}[idx] = val * {s}[idx];")?;
                    }
                    _ => {
                        writeln!(out, "            {res_name}[idx] = val;")?;
                    }
                }
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_softmax" && !inputs.is_empty() {
                let x = value_ident(module, inputs[0], names, counter);
                let dims = module.values[inputs[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&1);
                let rows = (res_len / cols).max(1);
                writeln!(out, "    for (int r = 0; r < {rows}; ++r) {{")?;
                writeln!(out, "        float sum = 0.0f;")?;
                writeln!(out, "        for (int c = 0; c < {cols}; ++c) {{")?;
                writeln!(out, "            float e = expf({x}[r * {cols} + c]);")?;
                writeln!(out, "            {res_name}[r * {cols} + c] = e;")?;
                writeln!(out, "            sum += e;")?;
                writeln!(out, "        }}")?;
                writeln!(
                    out,
                    "        for (int c = 0; c < {cols}; ++c) \
                     {res_name}[r * {cols} + c] /= sum;"
                )?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_rmsnorm" && !inputs.is_empty() {
                let x = value_ident(module, inputs[0], names, counter);
                let dims = module.values[inputs[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&1);
                let rows = (res_len / cols).max(1);
                let eps = match op.attributes.get("eps") {
                    Some(castforge_ir::Attribute::Float(f)) => *f as f32,
                    _ => 1e-5_f32,
                };
                writeln!(out, "    for (int r = 0; r < {rows}; ++r) {{")?;
                writeln!(out, "        float sq = 0.0f;")?;
                writeln!(out, "        for (int c = 0; c < {cols}; ++c) {{")?;
                writeln!(out, "            float v = {x}[r * {cols} + c];")?;
                writeln!(out, "            sq += v * v;")?;
                writeln!(out, "        }}")?;
                writeln!(
                    out,
                    "        float inv = 1.0f / sqrtf(sq / {cols}.0f + {eps:.6}f);"
                )?;
                if let Some(&w_id) = inputs.get(1) {
                    let w = value_ident(module, w_id, names, counter);
                    writeln!(
                        out,
                        "        for (int c = 0; c < {cols}; ++c) \
                         {res_name}[r * {cols} + c] = \
                         {x}[r * {cols} + c] * inv * {w}[r * {cols} + c];"
                    )?;
                } else {
                    writeln!(
                        out,
                        "        for (int c = 0; c < {cols}; ++c) \
                         {res_name}[r * {cols} + c] = {x}[r * {cols} + c] * inv;"
                    )?;
                }
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_swiglu" && inputs.len() >= 2 {
                let g = value_ident(module, inputs[0], names, counter);
                let u = value_ident(module, inputs[1], names, counter);
                writeln!(
                    out,
                    "    for (int i = 0; i < {res_len}; ++i) \
                     {res_name}[i] = ({g}[i] / (1.0f + expf(-{g}[i]))) * {u}[i];"
                )?;
            } else if name == "castforge.fused_rope" && inputs.len() >= 3 {
                let x = value_ident(module, inputs[0], names, counter);
                let c_arr = value_ident(module, inputs[1], names, counter);
                let s_arr = value_ident(module, inputs[2], names, counter);
                let dims = module.values[inputs[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&2);
                let rows = (res_len / cols).max(1);
                let half = cols / 2;
                writeln!(out, "    for (int r = 0; r < {rows}; ++r) {{")?;
                writeln!(out, "        for (int c = 0; c < {cols}; ++c) {{")?;
                writeln!(out, "            int idx = r * {cols} + c;")?;
                writeln!(
                    out,
                    "            float rot = (c < {half}) ? -{x}[idx + {half}] : {x}[idx - {half}];"
                )?;
                writeln!(
                    out,
                    "            {res_name}[idx] = {x}[idx] * {c_arr}[idx] + rot * {s_arr}[idx];"
                )?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_attention" && inputs.len() >= 3 {
                emit_c_fused_attention(
                    module, op, inputs[0], inputs[1], inputs[2], res_name, names, counter, out,
                )?;
            } else {
                let src = value_ident(module, inputs[0], names, counter);
                writeln!(
                    out,
                    "    for (int i = 0; i < {res_len}; ++i) {res_name}[i] = {src}[i];"
                )?;
            }
        }
        _ => {}
    }

    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_c_fused_attention(
    module: &Module,
    op: &castforge_ir::Operation,
    q_id: ValueId,
    k_id: ValueId,
    v_id: ValueId,
    res_name: &str,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
    out: &mut String,
) -> Result<()> {
    let q = value_ident(module, q_id, names, counter);
    let k = value_ident(module, k_id, names, counter);
    let v = value_ident(module, v_id, names, counter);
    let q_dims = module.values[q_id]
        .ty
        .as_tensor()
        .map(tensor_shape_dims)
        .unwrap_or_else(|| vec![1, 1]);
    let v_dims = module.values[v_id]
        .ty
        .as_tensor()
        .map(tensor_shape_dims)
        .unwrap_or_else(|| vec![1, 1]);
    let seq_q = *q_dims.first().unwrap_or(&1);
    let d_k = *q_dims.get(1).unwrap_or(&1);
    let seq_kv = *v_dims.first().unwrap_or(&1);
    let d_v = *v_dims.get(1).unwrap_or(&1);
    let scale = match op.attributes.get("scale") {
        Some(castforge_ir::Attribute::Float(f)) => *f as f32,
        _ => 1.0_f32,
    };
    let k_transposed = op
        .attributes
        .get("k_transposed")
        .is_some_and(|a| matches!(a, castforge_ir::Attribute::Bool(true)));
    let k_idx = if k_transposed {
        format!("c * {d_k} + kd")
    } else {
        format!("kd * {seq_kv} + c")
    };
    writeln!(out, "    for (int r = 0; r < {seq_q}; ++r) {{")?;
    writeln!(out, "        float scores[{seq_kv}];")?;
    writeln!(out, "        float max_s = -1e30f;")?;
    writeln!(out, "        for (int c = 0; c < {seq_kv}; ++c) {{")?;
    writeln!(out, "            float acc = 0.0f;")?;
    writeln!(
        out,
        "            for (int kd = 0; kd < {d_k}; ++kd) acc += {q}[r * {d_k} + kd] * {k}[{k_idx}];"
    )?;
    writeln!(out, "            scores[c] = acc * {scale:.6}f;")?;
    writeln!(out, "            if (scores[c] > max_s) max_s = scores[c];")?;
    writeln!(out, "        }}")?;
    writeln!(out, "        float sum = 0.0f;")?;
    writeln!(out, "        for (int c = 0; c < {seq_kv}; ++c) {{")?;
    writeln!(out, "            scores[c] = expf(scores[c] - max_s);")?;
    writeln!(out, "            sum += scores[c];")?;
    writeln!(out, "        }}")?;
    writeln!(out, "        for (int d = 0; d < {d_v}; ++d) {{")?;
    writeln!(out, "            float o_acc = 0.0f;")?;
    writeln!(
        out,
        "            for (int c = 0; c < {seq_kv}; ++c) \
         o_acc += (scores[c] / sum) * {v}[c * {d_v} + d];"
    )?;
    writeln!(out, "            {res_name}[r * {d_v} + d] = o_acc;")?;
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    Ok(())
}
