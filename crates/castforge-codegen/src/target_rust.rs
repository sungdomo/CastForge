use crate::{
    MemoryPlan, TargetConfig, build_memory_plan, sanitize_ident, tensor_len, tensor_shape_dims,
    value_ident,
};
use anyhow::{Result, anyhow};
use castforge_dialect_stablehlo::StableHloOp;
use castforge_ir::{DType, Module, OpId, ValueId};
use std::collections::HashMap;
use std::fmt::Write;

/// Standalone Rust Code Generator (`CodegenTarget::Rust`)
pub fn emit_rust_module(module: &Module) -> Result<String> {
    emit_rust_module_with_config(module, &TargetConfig::default())
}

/// Standalone Rust Code Generator parameterized by `TargetConfig`.
pub fn emit_rust_module_with_config(module: &Module, config: &TargetConfig) -> Result<String> {
    let mut out = String::new();
    let plan = build_memory_plan(module);
    let mod_name = module.name.as_deref().unwrap_or("castforge_model");

    writeln!(out, "// Auto-generated by CastForge Codegen (Target: Rust)")?;
    writeln!(
        out,
        "// Module: @{mod_name} | Constant Weights: {} B | Activation Workspace: {} B \
         (Naive: {} B, Saved: {} B across {} arena slots)",
        plan.total_constant_bytes,
        plan.total_activation_bytes,
        plan.naive_activation_bytes,
        plan.saved_activation_bytes(),
        plan.reusable_slot_count
    )?;
    if config.is_tiled() {
        writeln!(
            out,
            "// Hardware Config: Tiled GEMM ({}x{}x{}), SIMD Width: {} lanes",
            config.tile_m, config.tile_n, config.tile_k, config.simd_width
        )?;
    }
    writeln!(
        out,
        "#![allow(clippy::excessive_precision, unused_variables, clippy::identity_op)]\n"
    )?;

    for fn_op_id in module.functions() {
        emit_rust_func(module, fn_op_id, &plan, config, &mut out)?;
    }

    Ok(out)
}

fn r_idx(
    module: &Module,
    plan: &MemoryPlan,
    val_id: ValueId,
    idx_expr: &str,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
) -> String {
    if let Some(off) = plan.arena_f32_offset(val_id) {
        if off == 0 {
            format!("arena[{idx_expr}]")
        } else {
            format!("arena[{off} + {idx_expr}]")
        }
    } else {
        let name = value_ident(module, val_id, names, counter);
        format!("{name}[{idx_expr}]")
    }
}

fn emit_rust_func(
    module: &Module,
    fn_op_id: OpId,
    plan: &MemoryPlan,
    config: &TargetConfig,
    out: &mut String,
) -> Result<()> {
    let fn_op = &module.ops[fn_op_id];
    let fn_name = sanitize_ident(
        fn_op
            .attributes
            .get("sym_name")
            .and_then(|a| a.as_str())
            .unwrap_or("forward"),
    );

    let region_id = fn_op.regions[0];
    let block_id = module.regions[region_id].blocks[0];
    let block = &module.blocks[block_id];

    let mut names: HashMap<ValueId, String> = HashMap::new();
    let mut counter = 0usize;

    let mut params = Vec::new();
    for &arg_id in &block.arguments {
        let name = value_ident(module, arg_id, &mut names, &mut counter);
        let len = tensor_len(module, arg_id);
        params.push(format!("{name}: &[f32; {len}]"));
    }

    // Determine return value from last op (`func.return`)
    let mut ret_len = 1usize;
    let mut ret_val_opt = None;
    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("func", "return")
            && let Some(&ret_val) = op.operands.first()
        {
            ret_len = tensor_len(module, ret_val);
            ret_val_opt = Some(ret_val);
        }
    }

    writeln!(
        out,
        "pub fn {fn_name}({}) -> [f32; {ret_len}] {{",
        params.join(", ")
    )?;

    let arena_elems = plan.arena_f32_len();
    if arena_elems > 0 {
        writeln!(
            out,
            "    let mut arena = [0.0_f32; {arena_elems}]; // {} B shared activation workspace",
            plan.arena_workspace_bytes
        )?;
    }

    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("func", "return") {
            if let Some(ret_val) = ret_val_opt {
                if let Some(off) = plan.arena_f32_offset(ret_val) {
                    let end = off + ret_len;
                    writeln!(out, "    let mut out = [0.0_f32; {ret_len}];")?;
                    writeln!(out, "    out.copy_from_slice(&arena[{off}..{end}]);")?;
                    writeln!(out, "    out")?;
                } else {
                    let r_name = value_ident(module, ret_val, &mut names, &mut counter);
                    writeln!(out, "    *{r_name}")?;
                }
            }
            continue;
        }

        let res_val = match op.results.first() {
            Some(&v) => v,
            None => continue,
        };
        let res_name = value_ident(module, res_val, &mut names, &mut counter);
        let res_len = tensor_len(module, res_val);
        if let Some(alloc) = plan.allocation_for(res_val)
            && let (Some(slot), Some(off)) = (alloc.arena_slot, alloc.arena_offset)
        {
            let elem_off = off / 4;
            let tag = if alloc.inplace_from.is_some() {
                "arena:inplace"
            } else {
                "arena"
            };
            writeln!(
                out,
                "    // [{tag}] {res_name}: slot #{slot} @ offset {off} B \
                     (arena[{elem_off}..{}], live steps {}..={})",
                elem_off + res_len,
                alloc.first_def,
                alloc.last_use
            )?;
        }

        if op.is_op("stablehlo", "constant") {
            let t_ty = module.values[res_val]
                .ty
                .as_tensor()
                .ok_or_else(|| anyhow!("constant without tensor type"))?;
            let val_attr = op.attributes.get("value");

            if let DType::QuantUniform { .. } = &t_ty.dtype {
                let q_vals = val_attr
                    .and_then(|a| module.tensor_store.resolve_i8_attr(a, res_len))
                    .unwrap_or_else(|| vec![0; res_len]);
                let elems: Vec<String> = q_vals.iter().map(|v| v.to_string()).collect();
                writeln!(
                    out,
                    "    let {res_name}: [i8; {res_len}] = [{}];",
                    elems.join(", ")
                )?;
            } else {
                let vals = val_attr
                    .and_then(|a| module.tensor_store.resolve_f32_attr(a, res_len))
                    .unwrap_or_else(|| vec![0.0; res_len]);
                let elems: Vec<String> = vals.iter().map(|v| format!("{v:?}_f32")).collect();
                writeln!(
                    out,
                    "    let {res_name}: [f32; {res_len}] = [{}];",
                    elems.join(", ")
                )?;
            }
            continue;
        }

        if op.is_op("stablehlo", "uniform_dequantize") {
            let src_val = op.operands[0];
            let src_name = value_ident(module, src_val, &mut names, &mut counter);
            let (scale, zp) = match module.values[src_val].ty.as_tensor().map(|t| &t.dtype) {
                Some(DType::QuantUniform {
                    scale, zero_point, ..
                }) => (scale.parse::<f32>().unwrap_or(1.0), *zero_point),
                _ => (1.0, 0),
            };
            let dst = r_idx(module, plan, res_val, "i", &mut names, &mut counter);
            writeln!(out, "    for i in 0..{res_len} {{")?;
            writeln!(
                out,
                "        {dst} = ({src_name}[i] as i32 - {zp}) as f32 * {scale:?}_f32;"
            )?;
            writeln!(out, "    }}")?;
            continue;
        }

        emit_rust_hlo_op(
            module,
            plan,
            config,
            op_id,
            res_val,
            res_len,
            &mut names,
            &mut counter,
            out,
        )?;
    }

    writeln!(out, "}}")?;
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_rust_hlo_op(
    module: &Module,
    plan: &MemoryPlan,
    config: &TargetConfig,
    op_id: OpId,
    res_val: ValueId,
    res_len: usize,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
    out: &mut String,
) -> Result<()> {
    let op = &module.ops[op_id];
    let Some(hlo) = StableHloOp::from_op(op) else {
        return Ok(());
    };

    match hlo {
        StableHloOp::Add { lhs, rhs, .. }
        | StableHloOp::Subtract { lhs, rhs, .. }
        | StableHloOp::Multiply { lhs, rhs, .. }
        | StableHloOp::Divide { lhs, rhs, .. }
        | StableHloOp::Maximum { lhs, rhs, .. }
        | StableHloOp::Minimum { lhs, rhs, .. } => {
            let a = r_idx(module, plan, lhs, "i", names, counter);
            let b = r_idx(module, plan, rhs, "i", names, counter);
            let dst = r_idx(module, plan, res_val, "i", names, counter);
            let expr = match op.name.name.as_str() {
                "add" => format!("{a} + {b}"),
                "subtract" => format!("{a} - {b}"),
                "multiply" => format!("{a} * {b}"),
                "divide" => format!("{a} / {b}"),
                "maximum" => format!("({a}).max({b})"),
                _ => format!("({a}).min({b})"),
            };
            writeln!(out, "    for i in 0..{res_len} {{")?;
            writeln!(out, "        {dst} = {expr};")?;
            writeln!(out, "    }}")?;
        }
        StableHloOp::Exp { operand, .. }
        | StableHloOp::Tanh { operand, .. }
        | StableHloOp::Rsqrt { operand, .. }
        | StableHloOp::Convert { operand, .. }
        | StableHloOp::Reshape { operand, .. } => {
            let x = r_idx(module, plan, operand, "i", names, counter);
            let dst = r_idx(module, plan, res_val, "i", names, counter);
            let expr = match op.name.name.as_str() {
                "exponential" => format!("({x}).exp()"),
                "tanh" => format!("({x}).tanh()"),
                "rsqrt" => format!("1.0_f32 / ({x}).sqrt()"),
                _ => x,
            };
            writeln!(out, "    for i in 0..{res_len} {{")?;
            writeln!(out, "        {dst} = {expr};")?;
            writeln!(out, "    }}")?;
        }
        StableHloOp::Transpose {
            operand,
            permutation,
            ..
        } => {
            let in_dims = module.values[operand]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![res_len]);
            if in_dims.len() == 2 && permutation == vec![1, 0] {
                let (r, c) = (in_dims[0], in_dims[1]);
                let src = r_idx(
                    module,
                    plan,
                    operand,
                    &format!("r * {c} + c"),
                    names,
                    counter,
                );
                let dst = r_idx(
                    module,
                    plan,
                    res_val,
                    &format!("c * {r} + r"),
                    names,
                    counter,
                );
                writeln!(out, "    for r in 0..{r} {{")?;
                writeln!(out, "        for c in 0..{c} {{")?;
                writeln!(out, "            {dst} = {src};")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else {
                let src = r_idx(module, plan, operand, "i", names, counter);
                let dst = r_idx(module, plan, res_val, "i", names, counter);
                writeln!(out, "    for i in 0..{res_len} {{")?;
                writeln!(out, "        {dst} = {src};")?;
                writeln!(out, "    }}")?;
            }
        }
        StableHloOp::BroadcastInDim { operand, .. } => {
            let in_len = tensor_len(module, operand).max(1);
            let stride = (res_len / in_len).max(1);
            let src = r_idx(
                module,
                plan,
                operand,
                &format!("(i / {stride}) % {in_len}"),
                names,
                counter,
            );
            let dst = r_idx(module, plan, res_val, "i", names, counter);
            writeln!(out, "    for i in 0..{res_len} {{")?;
            writeln!(out, "        {dst} = {src};")?;
            writeln!(out, "    }}")?;
        }
        StableHloOp::Reduce {
            inputs,
            init_values,
            ..
        } => {
            let in_len = tensor_len(module, inputs[0]);
            let inner = (in_len / res_len.max(1)).max(1);
            let init0 = r_idx(module, plan, init_values[0], "0", names, counter);
            let src = r_idx(
                module,
                plan,
                inputs[0],
                &format!("o * {inner} + k"),
                names,
                counter,
            );
            let dst = r_idx(module, plan, res_val, "o", names, counter);
            writeln!(out, "    for o in 0..{res_len} {{")?;
            writeln!(out, "        let mut acc = {init0};")?;
            writeln!(out, "        for k in 0..{inner} {{")?;
            writeln!(out, "            acc += {src};")?;
            writeln!(out, "        }}")?;
            writeln!(out, "        {dst} = acc;")?;
            writeln!(out, "    }}")?;
        }
        StableHloOp::DotGeneral {
            lhs,
            rhs,
            dimension_numbers: dims,
            ..
        } => {
            let packed = dims.rhs_contracting_dimensions == [1];
            let lhs_dims = module.values[lhs]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![1, 1]);
            let rhs_dims = module.values[rhs]
                .ty
                .as_tensor()
                .map(tensor_shape_dims)
                .unwrap_or_else(|| vec![1, 1]);
            let m = *lhs_dims.first().unwrap_or(&1);
            let k = *lhs_dims.get(1).unwrap_or(&1);
            let n = if packed {
                *rhs_dims.first().unwrap_or(&1)
            } else {
                *rhs_dims.get(1).unwrap_or(&1)
            };
            let b_idx = if packed {
                format!("n * {k} + k")
            } else {
                format!("k * {n} + n")
            };
            let a = r_idx(module, plan, lhs, &format!("m * {k} + k"), names, counter);
            let b = r_idx(module, plan, rhs, &b_idx, names, counter);
            let dst = r_idx(
                module,
                plan,
                res_val,
                &format!("m * {n} + n"),
                names,
                counter,
            );
            if config.is_tiled() {
                let (tm, tn, tk) = (config.tile_m, config.tile_n, config.tile_k);
                writeln!(out, "    for m0 in (0..{m}).step_by({tm}) {{")?;
                writeln!(out, "        for n0 in (0..{n}).step_by({tn}) {{")?;
                writeln!(out, "            for m in m0..(m0 + {tm}).min({m}) {{")?;
                writeln!(out, "                for n in n0..(n0 + {tn}).min({n}) {{")?;
                writeln!(out, "                    let mut acc = 0.0_f32;")?;
                writeln!(
                    out,
                    "                    for k0 in (0..{k}).step_by({tk}) {{"
                )?;
                writeln!(
                    out,
                    "                        for k in k0..(k0 + {tk}).min({k}) {{"
                )?;
                writeln!(out, "                            acc += {a} * {b};")?;
                writeln!(out, "                        }}")?;
                writeln!(out, "                    }}")?;
                writeln!(out, "                    {dst} = acc;")?;
                writeln!(out, "                }}")?;
                writeln!(out, "            }}")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else {
                writeln!(out, "    for m in 0..{m} {{")?;
                writeln!(out, "        for n in 0..{n} {{")?;
                writeln!(out, "            let mut acc = 0.0_f32;")?;
                writeln!(out, "            for k in 0..{k} {{")?;
                writeln!(out, "                acc += {a} * {b};")?;
                writeln!(out, "            }}")?;
                writeln!(out, "            {dst} = acc;")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            }
        }
        StableHloOp::Composite { name, inputs, .. } => {
            if name == "castforge.fused_add_max" && inputs.len() == 3 {
                let a = r_idx(module, plan, inputs[0], "i", names, counter);
                let b = r_idx(module, plan, inputs[1], "i", names, counter);
                let c = r_idx(module, plan, inputs[2], "i", names, counter);
                let dst = r_idx(module, plan, res_val, "i", names, counter);
                writeln!(out, "    for i in 0..{res_len} {{")?;
                writeln!(out, "        {dst} = ({a} + {b}).max({c});")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_matmul_epilogue" && inputs.len() >= 3 {
                let packed = op
                    .attributes
                    .get("packed_rhs")
                    .is_some_and(|a| matches!(a, castforge_ir::Attribute::Bool(true)));
                let lhs_dims = module.values[inputs[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let rhs_dims = module.values[inputs[1]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let m = *lhs_dims.first().unwrap_or(&1);
                let k = *lhs_dims.get(1).unwrap_or(&1);
                let n = if packed {
                    *rhs_dims.first().unwrap_or(&1)
                } else {
                    *rhs_dims.get(1).unwrap_or(&1)
                };
                let b_idx = if packed {
                    format!("n * {k} + k")
                } else {
                    format!("k * {n} + n")
                };
                let a = r_idx(
                    module,
                    plan,
                    inputs[0],
                    &format!("m * {k} + k"),
                    names,
                    counter,
                );
                let b = r_idx(module, plan, inputs[1], &b_idx, names, counter);
                let bias = r_idx(module, plan, inputs[2], "idx", names, counter);
                let dst = r_idx(module, plan, res_val, "idx", names, counter);
                let epilogue = op
                    .attributes
                    .get("epilogue")
                    .and_then(|attr| attr.as_str())
                    .unwrap_or("bias");
                writeln!(out, "    for m in 0..{m} {{")?;
                writeln!(out, "        for n in 0..{n} {{")?;
                writeln!(out, "            let mut acc = 0.0_f32;")?;
                writeln!(out, "            for k in 0..{k} {{")?;
                writeln!(out, "                acc += {a} * {b};")?;
                writeln!(out, "            }}")?;
                writeln!(out, "            let idx = m * {n} + n;")?;
                writeln!(out, "            let val = acc + {bias};")?;
                match epilogue {
                    "bias_relu" if inputs.len() >= 4 => {
                        let z = r_idx(module, plan, inputs[3], "idx", names, counter);
                        writeln!(out, "            {dst} = val.max({z});")?;
                    }
                    "bias_tanh" => {
                        writeln!(out, "            {dst} = val.tanh();")?;
                    }
                    "bias_silu" => {
                        writeln!(out, "            {dst} = val / (1.0_f32 + (-val).exp());")?;
                    }
                    "bias_scale" if inputs.len() >= 4 => {
                        let s = r_idx(module, plan, inputs[3], "idx", names, counter);
                        writeln!(out, "            {dst} = val * ({s});")?;
                    }
                    _ => {
                        writeln!(out, "            {dst} = val;")?;
                    }
                }
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_softmax" && !inputs.is_empty() {
                let dims = module.values[res_val]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&1);
                let rows = (res_len / cols).max(1);
                let src = r_idx(
                    module,
                    plan,
                    inputs[0],
                    &format!("r * {cols} + c"),
                    names,
                    counter,
                );
                let dst = r_idx(
                    module,
                    plan,
                    res_val,
                    &format!("r * {cols} + c"),
                    names,
                    counter,
                );
                writeln!(out, "    for r in 0..{rows} {{")?;
                writeln!(out, "        let mut sum = 0.0_f32;")?;
                writeln!(out, "        for c in 0..{cols} {{")?;
                writeln!(out, "            let e = ({src}).exp();")?;
                writeln!(out, "            {dst} = e;")?;
                writeln!(out, "            sum += e;")?;
                writeln!(out, "        }}")?;
                writeln!(out, "        for c in 0..{cols} {{")?;
                writeln!(out, "            {dst} /= sum;")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_rmsnorm" && !inputs.is_empty() {
                let dims = module.values[res_val]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&1);
                let rows = (res_len / cols).max(1);
                let eps = match op.attributes.get("eps") {
                    Some(castforge_ir::Attribute::Float(f)) => *f as f32,
                    _ => 1e-5_f32,
                };
                let src = r_idx(
                    module,
                    plan,
                    inputs[0],
                    &format!("r * {cols} + c"),
                    names,
                    counter,
                );
                let dst = r_idx(
                    module,
                    plan,
                    res_val,
                    &format!("r * {cols} + c"),
                    names,
                    counter,
                );
                writeln!(out, "    for r in 0..{rows} {{")?;
                writeln!(out, "        let mut sq = 0.0_f32;")?;
                writeln!(out, "        for c in 0..{cols} {{")?;
                writeln!(out, "            let v = {src};")?;
                writeln!(out, "            sq += v * v;")?;
                writeln!(out, "        }}")?;
                writeln!(
                    out,
                    "        let inv = 1.0_f32 / (sq / {cols}.0_f32 + {eps:?}_f32).sqrt();"
                )?;
                writeln!(out, "        for c in 0..{cols} {{")?;
                if let Some(&w_id) = inputs.get(1) {
                    let w = r_idx(
                        module,
                        plan,
                        w_id,
                        &format!("r * {cols} + c"),
                        names,
                        counter,
                    );
                    writeln!(out, "            {dst} = ({src}) * inv * ({w});")?;
                } else {
                    writeln!(out, "            {dst} = ({src}) * inv;")?;
                }
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_swiglu" && inputs.len() >= 2 {
                let gate = r_idx(module, plan, inputs[0], "i", names, counter);
                let up = r_idx(module, plan, inputs[1], "i", names, counter);
                let dst = r_idx(module, plan, res_val, "i", names, counter);
                writeln!(out, "    for i in 0..{res_len} {{")?;
                writeln!(out, "        let g = {gate};")?;
                writeln!(
                    out,
                    "        {dst} = (g / (1.0_f32 + (-g).exp())) * ({up});"
                )?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_rope" && inputs.len() >= 3 {
                let dims = module.values[res_val]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, res_len]);
                let cols = *dims.last().unwrap_or(&res_len).max(&2);
                let rows = (res_len / cols).max(1);
                let half = cols / 2;
                let x_cur = r_idx(module, plan, inputs[0], "idx", names, counter);
                let x_hi = r_idx(
                    module,
                    plan,
                    inputs[0],
                    &format!("idx + {half}"),
                    names,
                    counter,
                );
                let x_lo = r_idx(
                    module,
                    plan,
                    inputs[0],
                    &format!("idx - {half}"),
                    names,
                    counter,
                );
                let c_cur = r_idx(module, plan, inputs[1], "idx", names, counter);
                let s_cur = r_idx(module, plan, inputs[2], "idx", names, counter);
                let dst = r_idx(module, plan, res_val, "idx", names, counter);
                writeln!(out, "    for r in 0..{rows} {{")?;
                writeln!(out, "        for c in 0..{cols} {{")?;
                writeln!(out, "            let idx = r * {cols} + c;")?;
                writeln!(
                    out,
                    "            let rot = if c < {half} {{ -{x_hi} }} else {{ {x_lo} }};"
                )?;
                writeln!(
                    out,
                    "            {dst} = {x_cur} * {c_cur} + rot * {s_cur};"
                )?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else if name == "castforge.fused_attention" && inputs.len() >= 3 {
                emit_rust_fused_attention(
                    module, plan, op, inputs[0], inputs[1], inputs[2], res_val, names, counter, out,
                )?;
            } else {
                let src = r_idx(module, plan, inputs[0], "i", names, counter);
                let dst = r_idx(module, plan, res_val, "i", names, counter);
                writeln!(out, "    for i in 0..{res_len} {{")?;
                writeln!(out, "        {dst} = {src};")?;
                writeln!(out, "    }}")?;
            }
        }
        _ => {}
    }

    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_rust_fused_attention(
    module: &Module,
    plan: &MemoryPlan,
    op: &castforge_ir::Operation,
    q_id: ValueId,
    k_id: ValueId,
    v_id: ValueId,
    res_val: ValueId,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
    out: &mut String,
) -> Result<()> {
    let q_dims = module.values[q_id]
        .ty
        .as_tensor()
        .map(tensor_shape_dims)
        .unwrap_or_else(|| vec![1, 1]);
    let v_dims = module.values[v_id]
        .ty
        .as_tensor()
        .map(tensor_shape_dims)
        .unwrap_or_else(|| vec![1, 1]);
    let seq_q = *q_dims.first().unwrap_or(&1);
    let d_k = *q_dims.get(1).unwrap_or(&1);
    let seq_kv = *v_dims.first().unwrap_or(&1);
    let d_v = *v_dims.get(1).unwrap_or(&1);
    let scale = match op.attributes.get("scale") {
        Some(castforge_ir::Attribute::Float(f)) => *f as f32,
        _ => 1.0_f32,
    };
    let k_transposed = op
        .attributes
        .get("k_transposed")
        .is_some_and(|a| matches!(a, castforge_ir::Attribute::Bool(true)));
    let q_idx = r_idx(
        module,
        plan,
        q_id,
        &format!("r * {d_k} + kd"),
        names,
        counter,
    );
    let k_idx_str = if k_transposed {
        format!("c * {d_k} + kd")
    } else {
        format!("kd * {seq_kv} + c")
    };
    let k_idx = r_idx(module, plan, k_id, &k_idx_str, names, counter);
    let v_idx = r_idx(
        module,
        plan,
        v_id,
        &format!("c * {d_v} + d"),
        names,
        counter,
    );
    let dst = r_idx(
        module,
        plan,
        res_val,
        &format!("r * {d_v} + d"),
        names,
        counter,
    );
    writeln!(out, "    for r in 0..{seq_q} {{")?;
    writeln!(out, "        let mut scores = [0.0_f32; {seq_kv}];")?;
    writeln!(out, "        let mut max_s = f32::NEG_INFINITY;")?;
    writeln!(out, "        for c in 0..{seq_kv} {{")?;
    writeln!(out, "            let mut acc = 0.0_f32;")?;
    writeln!(
        out,
        "            for kd in 0..{d_k} {{ acc += {q_idx} * {k_idx}; }}"
    )?;
    writeln!(out, "            let s = acc * {scale:?}_f32;")?;
    writeln!(out, "            scores[c] = s;")?;
    writeln!(out, "            if s > max_s {{ max_s = s; }}")?;
    writeln!(out, "        }}")?;
    writeln!(out, "        let mut sum = 0.0_f32;")?;
    writeln!(out, "        for c in 0..{seq_kv} {{")?;
    writeln!(out, "            scores[c] = (scores[c] - max_s).exp();")?;
    writeln!(out, "            sum += scores[c];")?;
    writeln!(out, "        }}")?;
    writeln!(out, "        for d in 0..{d_v} {{")?;
    writeln!(out, "            let mut o_acc = 0.0_f32;")?;
    writeln!(
        out,
        "            for c in 0..{seq_kv} {{ o_acc += (scores[c] / sum) * {v_idx}; }}"
    )?;
    writeln!(out, "            {dst} = o_acc;")?;
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    Ok(())
}
