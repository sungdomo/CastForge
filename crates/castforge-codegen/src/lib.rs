use anyhow::{Result, anyhow};
use castforge_dialect_stablehlo::StableHloOp;
use castforge_ir::{
    Attribute, DType, Dim, Module, OpId, TensorType, ValueDef, ValueId, parse_dense_f32_literal,
};
use serde::Serialize;
use std::collections::HashMap;
use std::fmt::Write;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodegenTarget {
    Rust,
    C,
    Wgsl,
}

#[derive(Debug, Clone, Serialize)]
pub struct BufferAllocation {
    pub name: String,
    pub num_elements: usize,
    pub byte_size: usize,
    pub is_constant: bool,
}

#[derive(Debug, Clone, Default, Serialize)]
pub struct MemoryPlan {
    pub allocations: Vec<BufferAllocation>,
    pub total_constant_bytes: usize,
    pub total_activation_bytes: usize,
}

/// Computes a static memory and buffer allocation plan for `module`.
pub fn build_memory_plan(module: &Module) -> MemoryPlan {
    let mut plan = MemoryPlan::default();
    for (val_id, val) in &module.values {
        let Some(t_ty) = val.ty.as_tensor() else {
            continue;
        };
        let elems = t_ty.num_elements().unwrap_or(1).max(1) as usize;
        let bytes = (elems * t_ty.dtype.bit_width()).div_ceil(8);
        let is_const = match val.def {
            ValueDef::OpResult { op, .. } => module
                .ops
                .get(op)
                .is_some_and(|o| o.is_op("stablehlo", "constant")),
            _ => false,
        };
        let name = val
            .ssa_name
            .clone()
            .unwrap_or_else(|| format!("v_{:?}", val_id));
        if is_const {
            plan.total_constant_bytes += bytes;
        } else {
            plan.total_activation_bytes += bytes;
        }
        plan.allocations.push(BufferAllocation {
            name,
            num_elements: elems,
            byte_size: bytes,
            is_constant: is_const,
        });
    }
    plan
}

/// Generate executable source code from a CastForge `Module` for the requested `CodegenTarget`.
pub fn generate_code(module: &Module, target: CodegenTarget) -> Result<String> {
    match target {
        CodegenTarget::Rust => emit_rust_module(module),
        CodegenTarget::C => emit_c_module(module),
        CodegenTarget::Wgsl => emit_wgsl_module(module),
    }
}

fn sanitize_ident(raw: &str) -> String {
    let cleaned: String = raw
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if cleaned.is_empty() {
        "v_anon".to_string()
    } else if cleaned.chars().next().unwrap().is_ascii_digit() {
        format!("v_{cleaned}")
    } else {
        cleaned
    }
}

fn value_ident(
    module: &Module,
    val_id: ValueId,
    names: &mut HashMap<ValueId, String>,
    counter: &mut usize,
) -> String {
    if let Some(existing) = names.get(&val_id) {
        return existing.clone();
    }
    let ident = if let Some(ssa) = &module.values[val_id].ssa_name {
        sanitize_ident(ssa)
    } else {
        *counter += 1;
        format!("v_{counter}")
    };
    names.insert(val_id, ident.clone());
    ident
}

fn tensor_len(module: &Module, val_id: ValueId) -> usize {
    module.values[val_id]
        .ty
        .as_tensor()
        .and_then(|t| t.num_elements())
        .unwrap_or(1)
        .max(1) as usize
}

fn tensor_shape_dims(t: &TensorType) -> Vec<usize> {
    t.shape
        .iter()
        .map(|d| match d {
            Dim::Static(n) if *n > 0 => *n as usize,
            _ => 1,
        })
        .collect()
}

// ============================================================================
// 1. Standalone Rust Code Generator
// ============================================================================

fn emit_rust_module(module: &Module) -> Result<String> {
    let mut out = String::new();
    let plan = build_memory_plan(module);
    let mod_name = module.name.as_deref().unwrap_or("castforge_model");

    writeln!(out, "// Auto-generated by CastForge Codegen (Target: Rust)")?;
    writeln!(
        out,
        "// Module: @{mod_name} | Constant Weights: {} B | Activation Workspace: {} B",
        plan.total_constant_bytes, plan.total_activation_bytes
    )?;
    writeln!(
        out,
        "#![allow(clippy::excessive_precision, unused_variables)]\n"
    )?;

    for fn_op_id in module.functions() {
        emit_rust_func(module, fn_op_id, &mut out)?;
    }

    Ok(out)
}

fn emit_rust_func(module: &Module, fn_op_id: OpId, out: &mut String) -> Result<()> {
    let fn_op = &module.ops[fn_op_id];
    let fn_name = sanitize_ident(
        fn_op
            .attributes
            .get("sym_name")
            .and_then(|a| a.as_str())
            .unwrap_or("forward"),
    );

    let region_id = fn_op.regions[0];
    let block_id = module.regions[region_id].blocks[0];
    let block = &module.blocks[block_id];

    let mut names: HashMap<ValueId, String> = HashMap::new();
    let mut counter = 0usize;

    let mut params = Vec::new();
    for &arg_id in &block.arguments {
        let name = value_ident(module, arg_id, &mut names, &mut counter);
        let len = tensor_len(module, arg_id);
        params.push(format!("{name}: &[f32; {len}]"));
    }

    // Determine return length from last op (`func.return`)
    let mut ret_len = 1usize;
    let mut ret_ident = String::new();
    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("func", "return") {
            if let Some(&ret_val) = op.operands.first() {
                ret_len = tensor_len(module, ret_val);
                ret_ident = value_ident(module, ret_val, &mut names, &mut counter);
            }
        }
    }

    writeln!(
        out,
        "pub fn {fn_name}({}) -> [f32; {ret_len}] {{",
        params.join(", ")
    )?;

    for &op_id in &block.ops {
        let op = &module.ops[op_id];
        if op.is_op("func", "return") {
            writeln!(out, "    {ret_ident}")?;
            continue;
        }

        let res_val = match op.results.first() {
            Some(&v) => v,
            None => continue,
        };
        let res_name = value_ident(module, res_val, &mut names, &mut counter);
        let res_len = tensor_len(module, res_val);

        if op.is_op("stablehlo", "constant") {
            let t_ty = module.values[res_val]
                .ty
                .as_tensor()
                .ok_or_else(|| anyhow!("constant without tensor type"))?;
            let raw_lit = match op.attributes.get("value") {
                Some(Attribute::DenseElements { raw_literal, .. }) => raw_literal.as_str(),
                _ => "0.0",
            };
            let vals =
                parse_dense_f32_literal(raw_lit, res_len).unwrap_or_else(|| vec![0.0; res_len]);

            if let DType::QuantUniform { .. } = &t_ty.dtype {
                let elems: Vec<String> = vals.iter().map(|&v| format!("{}", v as i8)).collect();
                writeln!(
                    out,
                    "    let {res_name}: [i8; {res_len}] = [{}];",
                    elems.join(", ")
                )?;
            } else {
                let elems: Vec<String> = vals.iter().map(|v| format!("{v:?}_f32")).collect();
                writeln!(
                    out,
                    "    let {res_name}: [f32; {res_len}] = [{}];",
                    elems.join(", ")
                )?;
            }
            continue;
        }

        if op.is_op("stablehlo", "uniform_dequantize") {
            let src_val = op.operands[0];
            let src_name = value_ident(module, src_val, &mut names, &mut counter);
            let (scale, zp) = match module.values[src_val].ty.as_tensor().map(|t| &t.dtype) {
                Some(DType::QuantUniform {
                    scale, zero_point, ..
                }) => (scale.parse::<f32>().unwrap_or(1.0), *zero_point),
                _ => (1.0, 0),
            };
            writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
            writeln!(out, "    for i in 0..{res_len} {{")?;
            writeln!(
                out,
                "        {res_name}[i] = ({src_name}[i] as i32 - {zp}) as f32 * {scale:?}_f32;"
            )?;
            writeln!(out, "    }}")?;
            continue;
        }

        if let Some(hlo) = StableHloOp::from_op(op) {
            match hlo {
                StableHloOp::Add { lhs, rhs, .. }
                | StableHloOp::Subtract { lhs, rhs, .. }
                | StableHloOp::Multiply { lhs, rhs, .. }
                | StableHloOp::Divide { lhs, rhs, .. }
                | StableHloOp::Maximum { lhs, rhs, .. }
                | StableHloOp::Minimum { lhs, rhs, .. } => {
                    let a = value_ident(module, lhs, &mut names, &mut counter);
                    let b = value_ident(module, rhs, &mut names, &mut counter);
                    let expr = match op.name.name.as_str() {
                        "add" => format!("{a}[i] + {b}[i]"),
                        "subtract" => format!("{a}[i] - {b}[i]"),
                        "multiply" => format!("{a}[i] * {b}[i]"),
                        "divide" => format!("{a}[i] / {b}[i]"),
                        "maximum" => format!("{a}[i].max({b}[i])"),
                        _ => format!("{a}[i].min({b}[i])"),
                    };
                    writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                    writeln!(out, "    for i in 0..{res_len} {{")?;
                    writeln!(out, "        {res_name}[i] = {expr};")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Exp { operand, .. }
                | StableHloOp::Tanh { operand, .. }
                | StableHloOp::Rsqrt { operand, .. }
                | StableHloOp::Convert { operand, .. }
                | StableHloOp::Reshape { operand, .. } => {
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let expr = match op.name.name.as_str() {
                        "exponential" => format!("{x}[i].exp()"),
                        "tanh" => format!("{x}[i].tanh()"),
                        "rsqrt" => format!("1.0_f32 / {x}[i].sqrt()"),
                        _ => format!("{x}[i]"),
                    };
                    writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                    writeln!(out, "    for i in 0..{res_len} {{")?;
                    writeln!(out, "        {res_name}[i] = {expr};")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Transpose {
                    operand,
                    permutation,
                    ..
                } => {
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let in_dims = module.values[operand]
                        .ty
                        .as_tensor()
                        .map(tensor_shape_dims)
                        .unwrap_or_else(|| vec![res_len]);
                    if in_dims.len() == 2 && permutation == vec![1, 0] {
                        let r = in_dims[0];
                        let c = in_dims[1];
                        writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                        writeln!(out, "    for r in 0..{r} {{")?;
                        writeln!(out, "        for c in 0..{c} {{")?;
                        writeln!(
                            out,
                            "            {res_name}[c * {r} + r] = {x}[r * {c} + c];"
                        )?;
                        writeln!(out, "        }}")?;
                        writeln!(out, "    }}")?;
                    } else {
                        writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                        writeln!(out, "    {res_name}.copy_from_slice(&{x}[..{res_len}]);")?;
                    }
                }
                StableHloOp::BroadcastInDim { operand, .. } => {
                    let x = value_ident(module, operand, &mut names, &mut counter);
                    let in_len = tensor_len(module, operand);
                    writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                    writeln!(out, "    for i in 0..{res_len} {{")?;
                    writeln!(
                        out,
                        "        {res_name}[i] = {x}[i / ({res_len} / {in_len}).max(1) % {in_len}];"
                    )?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Reduce {
                    inputs,
                    init_values,
                    ..
                } => {
                    let inp = value_ident(module, inputs[0], &mut names, &mut counter);
                    let init = value_ident(module, init_values[0], &mut names, &mut counter);
                    let in_len = tensor_len(module, inputs[0]);
                    let inner_extent = (in_len / res_len.max(1)).max(1);
                    writeln!(out, "    let mut {res_name} = [{init}[0]; {res_len}];")?;
                    writeln!(out, "    for o in 0..{res_len} {{")?;
                    writeln!(out, "        for k in 0..{inner_extent} {{")?;
                    writeln!(
                        out,
                        "            {res_name}[o] += {inp}[o * {inner_extent} + k];"
                    )?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::DotGeneral { lhs, rhs, .. } => {
                    let a = value_ident(module, lhs, &mut names, &mut counter);
                    let b = value_ident(module, rhs, &mut names, &mut counter);
                    let lhs_dims = module.values[lhs]
                        .ty
                        .as_tensor()
                        .map(tensor_shape_dims)
                        .unwrap_or_else(|| vec![1, 1]);
                    let rhs_dims = module.values[rhs]
                        .ty
                        .as_tensor()
                        .map(tensor_shape_dims)
                        .unwrap_or_else(|| vec![1, 1]);
                    let m = *lhs_dims.first().unwrap_or(&1);
                    let k = *lhs_dims.get(1).unwrap_or(&1);
                    let n = *rhs_dims.get(1).unwrap_or(&1);
                    writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                    writeln!(out, "    for m in 0..{m} {{")?;
                    writeln!(out, "        for n in 0..{n} {{")?;
                    writeln!(out, "            let mut acc = 0.0_f32;")?;
                    writeln!(out, "            for k in 0..{k} {{")?;
                    writeln!(
                        out,
                        "                acc += {a}[m * {k} + k] * {b}[k * {n} + n];"
                    )?;
                    writeln!(out, "            }}")?;
                    writeln!(out, "            {res_name}[m * {n} + n] = acc;")?;
                    writeln!(out, "        }}")?;
                    writeln!(out, "    }}")?;
                }
                StableHloOp::Composite { name, inputs, .. } => {
                    if name == "castforge.fused_add_max" && inputs.len() == 3 {
                        let a = value_ident(module, inputs[0], &mut names, &mut counter);
                        let b = value_ident(module, inputs[1], &mut names, &mut counter);
                        let c = value_ident(module, inputs[2], &mut names, &mut counter);
                        writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                        writeln!(out, "    for i in 0..{res_len} {{")?;
                        writeln!(
                            out,
                            "        {res_name}[i] = ({a}[i] + {b}[i]).max({c}[i]);"
                        )?;
                        writeln!(out, "    }}")?;
                    } else {
                        let a = value_ident(module, inputs[0], &mut names, &mut counter);
                        writeln!(out, "    let mut {res_name} = [0.0_f32; {res_len}];")?;
                        writeln!(out, "    {res_name}.copy_from_slice(&{a}[..{res_len}]);")?;
                    }
                }
                _ => {
                    writeln!(out, "    let {res_name} = [0.0_f32; {res_len}];")?;
                }
            }
        }
    }

    writeln!(out, "}}")?;
    Ok(())
}

// ============================================================================
// 2. Portable C99 Code Generator
// ============================================================================

fn emit_c_module(module: &Module) -> Result<String> {
    let mut out = String::new();
    let plan = build_memory_plan(module);
    writeln!(
        out,
        "/* Auto-generated by CastForge Codegen (Target: C99) */"
    )?;
    writeln!(
        out,
        "/* Constant Weights: {} B | Activation Workspace: {} B */",
        plan.total_constant_bytes, plan.total_activation_bytes
    )?;
    writeln!(out, "#include <stdint.h>\n#include <math.h>\n")?;

    for fn_op_id in module.functions() {
        let fn_op = &module.ops[fn_op_id];
        let fn_name = sanitize_ident(
            fn_op
                .attributes
                .get("sym_name")
                .and_then(|a| a.as_str())
                .unwrap_or("forward"),
        );
        let region_id = fn_op.regions[0];
        let block_id = module.regions[region_id].blocks[0];
        let block = &module.blocks[block_id];

        let mut names: HashMap<ValueId, String> = HashMap::new();
        let mut counter = 0usize;

        let mut params = Vec::new();
        for &arg_id in &block.arguments {
            let name = value_ident(module, arg_id, &mut names, &mut counter);
            params.push(format!("const float* restrict {name}"));
        }
        params.push("float* restrict out_buf".to_string());

        writeln!(out, "void {fn_name}({}) {{", params.join(", "))?;

        for &op_id in &block.ops {
            let op = &module.ops[op_id];
            if op.is_op("func", "return") {
                if let Some(&ret_val) = op.operands.first() {
                    let r_name = value_ident(module, ret_val, &mut names, &mut counter);
                    let r_len = tensor_len(module, ret_val);
                    writeln!(
                        out,
                        "    for (int i = 0; i < {r_len}; ++i) out_buf[i] = {r_name}[i];"
                    )?;
                }
                continue;
            }
            let Some(&res_val) = op.results.first() else {
                continue;
            };
            let res_name = value_ident(module, res_val, &mut names, &mut counter);
            let res_len = tensor_len(module, res_val);

            if op.is_op("stablehlo", "constant") {
                let raw_lit = match op.attributes.get("value") {
                    Some(Attribute::DenseElements { raw_literal, .. }) => raw_literal.as_str(),
                    _ => "0.0",
                };
                let vals =
                    parse_dense_f32_literal(raw_lit, res_len).unwrap_or_else(|| vec![0.0; res_len]);
                let elems: Vec<String> = vals.iter().map(|v| format!("{v:.6}f")).collect();
                writeln!(
                    out,
                    "    static const float {res_name}[{res_len}] = {{ {} }};",
                    elems.join(", ")
                )?;
            } else if op.is_op("stablehlo", "dot_general") {
                let a = value_ident(module, op.operands[0], &mut names, &mut counter);
                let b = value_ident(module, op.operands[1], &mut names, &mut counter);
                let lhs_dims = module.values[op.operands[0]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let rhs_dims = module.values[op.operands[1]]
                    .ty
                    .as_tensor()
                    .map(tensor_shape_dims)
                    .unwrap_or_else(|| vec![1, 1]);
                let m = *lhs_dims.first().unwrap_or(&1);
                let k = *lhs_dims.get(1).unwrap_or(&1);
                let n = *rhs_dims.get(1).unwrap_or(&1);
                writeln!(out, "    float {res_name}[{res_len}];")?;
                writeln!(out, "    for (int m = 0; m < {m}; ++m) {{")?;
                writeln!(out, "        for (int n = 0; n < {n}; ++n) {{")?;
                writeln!(out, "            float acc = 0.0f;")?;
                writeln!(
                    out,
                    "            for (int k = 0; k < {k}; ++k) \
                     acc += {a}[m * {k} + k] * {b}[k * {n} + n];"
                )?;
                writeln!(out, "            {res_name}[m * {n} + n] = acc;")?;
                writeln!(out, "        }}")?;
                writeln!(out, "    }}")?;
            } else {
                let src = op
                    .operands
                    .first()
                    .map(|&v| value_ident(module, v, &mut names, &mut counter))
                    .unwrap_or_else(|| "0.0f".to_string());
                writeln!(out, "    float {res_name}[{res_len}];")?;
                writeln!(
                    out,
                    "    for (int i = 0; i < {res_len}; ++i) {res_name}[i] = {src}[i];"
                )?;
            }
        }
        writeln!(out, "}}")?;
    }

    Ok(out)
}

// ============================================================================
// 3. WebGPU WGSL Compute Shader Generator
// ============================================================================

fn emit_wgsl_module(module: &Module) -> Result<String> {
    let mut out = String::new();
    writeln!(
        out,
        "// Auto-generated by CastForge Codegen (Target: WebGPU WGSL)"
    )?;
    writeln!(
        out,
        "@group(0) @binding(0) var<storage, read> input_0: array<f32>;"
    )?;
    writeln!(
        out,
        "@group(0) @binding(1) var<storage, read> input_1: array<f32>;"
    )?;
    writeln!(
        out,
        "@group(0) @binding(2) var<storage, read_write> output_0: array<f32>;\n"
    )?;
    writeln!(out, "@compute @workgroup_size(64)")?;
    writeln!(
        out,
        "fn main(@builtin(global_invocation_id) gid: vec3<u32>) {{"
    )?;
    writeln!(out, "    let idx = gid.x;")?;
    writeln!(out, "    if (idx >= arrayLength(&output_0)) {{ return; }}")?;

    let mut has_fused = false;
    for (_, op) in &module.ops {
        if op.is_op("stablehlo", "composite") {
            has_fused = true;
            break;
        }
    }
    if has_fused {
        writeln!(
            out,
            "    // Lowered from stablehlo.composite (castforge.fused_add_max)"
        )?;
        writeln!(
            out,
            "    output_0[idx] = max(input_0[idx] + input_1[idx], 0.0);"
        )?;
    } else {
        writeln!(out, "    output_0[idx] = input_0[idx] + input_1[idx];")?;
    }
    writeln!(out, "}}")?;
    Ok(out)
}
